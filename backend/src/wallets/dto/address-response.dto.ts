import { ApiProperty } from '@nestjs/swagger';

export class AddressResponseDto {
  @ApiProperty({
    example: '0x8f3c...d91a',
    description: 'Network-level receiving address generated by Roqqu',
  })
  address!: string;

  @ApiProperty({ example: 'erc20' })
  network!: string;

  @ApiProperty({
    example: false,
    description:
      'True when the invoice already had an address and Roqqu was not called again',
  })
  reused!: boolean;
}
